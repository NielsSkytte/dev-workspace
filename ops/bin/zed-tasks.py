"""Write one Zed task per project into %APPDATA%\\Zed\\tasks.json.

alt-a a opens Zed's task picker; type part of the project, Enter. The task runs
ops/bin/zed-agent.ps1 -Project <dir>, which asks for the agent in the terminal.
Zed names the tab after the task label: the project folder name only.
Projects = folders with a CLAUDE.md under customers\\ and own\\ (dot-folders skipped).
Hand-written tasks (no -Project argument) are kept. Run automatically by
ops/bin/heal-repos.ps1 (so by /new-project and every /log).
"""
import json
import os
from pathlib import Path

DEV = Path("C:/Dev")
TASKS = Path(os.environ["APPDATA"]) / "Zed" / "tasks.json"

OLD = ("📁", "🟦", "🟪", "🟩")  # labels of earlier generated layouts
LAUNCHER = "C:/Dev/ops/bin/zed-agent.ps1"


def projects():
    found = set()
    for top in ("customers", "own"):
        for md in (DEV / top).glob("**/CLAUDE.md"):
            rel = md.parent.relative_to(DEV)
            if len(rel.parts) <= 3 and not any(p.startswith(".") for p in rel.parts):
                found.add(md.parent)
    return sorted(found, key=lambda p: str(p).lower())


def title(proj):
    """Last folder only: customers/Matas/DataCompare -> DataCompare, customers/Matas -> Matas, own/X -> X."""
    return proj.name


def main():
    text = TASKS.read_text(encoding="utf-8") if TASKS.exists() else "[]"
    body = "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("//"))
    kept = [t for t in json.loads(body)
            if "-Project" not in t.get("args", []) and not t.get("label", "").startswith(OLD)]
    generated = []
    for proj in projects():
        generated.append({
            "label": title(proj),
            "command": "powershell",
            "args": ["-NoProfile", "-ExecutionPolicy", "Bypass", "-File", LAUNCHER,
                     "-Project", str(proj)],
            "cwd": str(proj),
            "use_new_terminal": True,
            "allow_concurrent_runs": True,
            "reveal_target": "center",
            "hide": "never",
            "show_summary": False,
            "show_command": False,
            "tags": [str(proj.relative_to(DEV))],
        })
    header = ("// Generated by C:/Dev/ops/bin/zed-tasks.py (one task per project); "
              "hand-written tasks are kept.\n")
    TASKS.write_text(header + json.dumps(kept + generated, indent=2, ensure_ascii=False) + "\n",
                     encoding="utf-8")
    print(f"{len(generated)} generated, {len(kept)} kept -> {TASKS}")


if __name__ == "__main__":
    main()
