"""Write one Zed task per project x agent into %APPDATA%\\Zed\\tasks.json.

Zed names a task tab after the task label and ignores the terminal title, so the
label carries the project name and a coloured square for the agent. alt-a a opens
Zed's task picker; type part of the project and agent (e.g. "matas priv").
Projects = folders with a CLAUDE.md under customers\\ and own\\ (dot-folders skipped).
Hand-written tasks (labels without the agent squares) are kept. Re-run after adding
a project: python C:/Dev/ops/bin/zed-tasks.py
"""
import json
import os
from pathlib import Path

DEV = Path("C:/Dev")
TASKS = Path(os.environ["APPDATA"]) / "Zed" / "tasks.json"

AGENTS = [  # (square, name, command, args, env)
    ("\U0001F7E6", "Claude", "claude", [], {}),
    ("\U0001F7EA", "Claude priv", "claude", [],
     {"CLAUDE_CONFIG_DIR": str(Path.home() / ".claude-priv")}),
    ("\U0001F7E9", "Gemini", "powershell", ["-NoProfile", "-Command", "gemini"], {}),
]
SQUARES = tuple(a[0] for a in AGENTS)


def projects():
    found = set()
    for top in ("customers", "own"):
        for md in (DEV / top).glob("**/CLAUDE.md"):
            rel = md.parent.relative_to(DEV)
            if len(rel.parts) <= 3 and not any(p.startswith(".") for p in rel.parts):
                found.add(md.parent)
    return sorted(found, key=lambda p: str(p).lower())


def main():
    text = TASKS.read_text(encoding="utf-8") if TASKS.exists() else "[]"
    body = "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("//"))
    kept = [t for t in json.loads(body) if not t.get("label", "").startswith(SQUARES)]
    generated = []
    for proj in projects():
        for square, name, cmd, args, env in AGENTS:
            generated.append({
                "label": f"{square} {proj.name} \u00b7 {name}",
                "command": cmd,
                "args": args,
                "cwd": str(proj),
                "env": dict(env, CLAUDE_CODE_DISABLE_TERMINAL_TITLE="1"),
                "use_new_terminal": True,
                "allow_concurrent_runs": True,
                "reveal_target": "center",
                "hide": "never",
                "show_summary": False,
                "show_command": False,
                "tags": [str(proj.relative_to(DEV))],
            })
    header = ("// Generated by C:/Dev/ops/bin/zed-tasks.py (project x agent tasks); "
              "hand-written tasks are kept.\n")
    TASKS.write_text(header + json.dumps(kept + generated, indent=2, ensure_ascii=False) + "\n",
                     encoding="utf-8")
    print(f"{len(generated)} generated, {len(kept)} kept -> {TASKS}")


if __name__ == "__main__":
    main()
