"""What F&O requires, and the two write paths that make a short line typeable.

The readiness gate decides whether a month can be entered at all, so its rules are worth
holding down: a placeholder is not a value, a customer with no rule requires nothing, and
internal time is never short of anything because it is never entered.

The write paths are held to the same standard as the TODO and task-file ones: a correction
changes the line it names and leaves every other byte -- the file's own prose, its earlier
correction notes, a comment on a field -- exactly as it was.
"""
